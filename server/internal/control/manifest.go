// GenerateConnectorManifest renders a complete K8s manifest from the onboarding
// form input. The signing key is intentionally NOT included; admins must create
// the pam-task-signing Secret separately so the key never flows through pam-control.
func GenerateConnectorManifest(cfg OnboardConfig) (string, error) {
	if err := validateOnboardConfig(cfg); err != nil {
		return "", err
	}
	funcs := template.FuncMap{"join": strings.Join}
	tmpl, err := template.New("connector-manifest").Funcs(funcs).Parse(manifestTemplate)
	if err != nil {
		return "", fmt.Errorf("parse manifest template: %w", err)
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, cfg); err != nil {
		return "", fmt.Errorf("render manifest template: %w", err)
	}
	return buf.String(), nil
}

func validateOnboardConfig(cfg OnboardConfig) error {
	if strings.TrimSpace(cfg.Name) == "" {
		return fmt.Errorf("name is required")
	}
	if !validEnvironment(cfg.Environment, false) {
		return fmt.Errorf("environment must be development, testing or production")
	}
	if strings.TrimSpace(cfg.ConnectorNamespace) == "" {
		return fmt.Errorf("connectorNamespace is required")
	}
	if len(cfg.AllowedNamespaces) == 0 {
		return fmt.Errorf("allowedNamespaces must not be empty")
	}
	for _, ns := range cfg.AllowedNamespaces {
		ns = strings.TrimSpace(ns)
		if ns == "" {
			return fmt.Errorf("allowedNamespaces contains an empty entry")
		}
		if ns == "*" {
			return fmt.Errorf("wildcard namespace is not allowed")
		}
	}
	if strings.TrimSpace(cfg.ControlURL) == "" {
		return fmt.Errorf("controlURL is required")
	}
	if strings.TrimSpace(cfg.TokenAudience) == "" {
		return fmt.Errorf("tokenAudience is required")
	}
	if strings.TrimSpace(cfg.ExecutionServiceAccount) == "" {
		return fmt.Errorf("executionServiceAccount is required")
	}
	return nil
}
